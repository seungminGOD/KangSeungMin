# 실습 2. 강한 상관 쌍 찾기
# 상관 행렬에서 절댓값이 큰 센서 쌍을 자동으로 추출

# · 여러 지표 열로 상관 행렬을 만들기
# "%02d"는 10진수(decimal)를 두자리로 만들어 포함시키라는 뜻
feat = ['지표%02d' % i for i in range(1,11)]
print(feat)
# ['지표01', '지표02', '지표03', '지표04', '지표05', '지표06', '지표07', '지표08', '지표09', '지표10']

cm = df[feat].corr().round(3)
print(cm)
#        지표01   지표02   지표03   지표04   지표05   지표06   지표07   지표08   지표09   지표10
