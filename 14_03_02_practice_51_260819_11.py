# 지표10  0.999  0.935  0.696 -0.979 -0.882  0.300 -0.868  0.740 -0.951  1.000

# · 이중 반복으로 대각선을 제외한 각 쌍의 상관계수 확인
# 위 cm 자료에서 0.4 이상의 상관관계가 크다 판단되는 경우를 뽑아보기
for i in range(len(cm.columns)):
    print(f"{i}번째 컬럼 이름 {cm.columns[i]}") # 0번째 컬럼 이름 지표01

    # i + 1번부터 챙겨 비교해야, 대각선 중심의 반대편을 중복 비교하지 않게 할 수 있다
    for j in range(i + 1, len(cm.columns)):

        c = cm.iloc[i, j]

        # print(f"{i}번째 컬럼 {cm.columns[i]}과 비교할 {cm.columns[j]} : {c}") 
        # 8번째 컬럼 지표09과 비교할 지표10 : -0.951

        # abs로 - 부호 없는 절대값 만들기
        if abs(c) > 0.4:
            print(f"{i}번째 컬럼 {cm.columns[i]}과 비교할 {cm.columns[j]} : {c} -> 강한 상관계수") 

            # 여러분이 원하시면 이 내용들을 바로 출력하지 말고
            # 별도의 배열을 만들어 해당 배열에 결과를 추가하고
            # 반복문이 끝나면 바깥에서 출력 처리 및 가장 큰 값도 찾고, 강한쌍이 몇개인지도 출력 (선택가능한 심화문제)

