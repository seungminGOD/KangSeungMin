# 지표04 -0.983 -0.940 -0.705  1.000  0.887 -0.333  0.873 -0.750  0.949 -0.979
# 지표05 -0.895 -0.930 -0.950  0.887  1.000 -0.709  0.999 -0.966  0.982 -0.882
