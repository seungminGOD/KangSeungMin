import pandas as pd

# =========================================================
# 실습 1. 평균·분산·표준편차 구하기
# 전체와 라인별로 평균·분산·표준편차 구하기
# =========================================================
print("=========================================================")
print("실습 1. 평균·분산·표준편차 구하기")
print("전체와 라인별로 평균·분산·표준편차 구하기")
print("=========================================================")

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 진동 열 전체의 평균·분산·표준편차
print(df["진동"].mean().round(3))
print(df["진동"].var().round(3))
print(df["진동"].std().round(3))

# 라인(냉각기상태)별 평균과 표준편차 비교
print(df.groupby("냉각기상태")["진동"].mean().round(3))
print(df.groupby("냉각기상태")["진동"].std().round(3))
print(df.groupby("냉각기상태")["진동"].agg(["mean", "std"]).round(3))

# 이름 붙여 정리하기 (권장 방식)
print(
    df.groupby("냉각기상태")
    .agg(평균=("진동", "mean"), 표준편차=("진동", "std"))
    .round(3)
)


# =========================================================
# 실습 2. 그룹별 통계 응용
# qc 합격·불합격 그룹별 지표 통계 비교
# =========================================================
print("=========================================================")
print("실습 2. 그룹별 통계 응용")
print("qc 합격·불합격 그룹별 지표 통계 비교")
print("=========================================================")

df = pd.read_csv("data/14_hydraulic_qc.csv", encoding="utf-8")

feats = ["지표01", "지표05"]

# 판정(검사결과)별 주요 지표 평균
print(df.groupby("검사결과")[feats].mean().round(2))

# 같은 그룹 기준 표준편차 비교
print(df.groupby("검사결과")[feats].std().round(2))

# 지표1, 지표5 모두 합격이 불합격보다 표준편차가 훨씬 작음


# =========================================================
# 실습 3. agg로 여러 통계 한 번에
# 리스트·이름붙이기 두 방식으로 여러 통계 요약
# =========================================================
print("=========================================================")
print("실습 3. agg로 여러 통계 한 번에")
print("리스트·이름붙이기 두 방식으로 여러 통계 요약")
print("=========================================================")

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 운전부하별 진동의 평균·표준편차·최댓값 (리스트 방식)
print(df.groupby("운전부하")["진동"].agg(["mean", "std", "max"]).round(3))

# 밸브상태별 평균온도·평균진동·측정수 (이름 붙이기 방식)
print(
    df.groupby("밸브상태")
    .agg(
        평균온도=("온도", "mean"),
        평균진동=("진동", "mean"),
        측정수=("온도", "count"),
    )
    .round(3)
)


# =========================================================
# 실습 4. agg 진단표 만들기
# 이름 붙인 agg로 설비 진단표를 만들고 정렬
# =========================================================
print("=========================================================")
print("실습 4. agg 진단표 만들기")
print("이름 붙인 agg로 설비 진단표를 만들고 정렬")
print("=========================================================")

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

report = (
    df.groupby("밸브상태")
    .agg(
        측정수=("온도", "count"),
        평균온도=("온도", "mean"),
        온도편차=("온도", "std"),
        평균진동=("진동", "mean"),
        평균압력=("압력", "mean"),
    )
    .round(2)
)
print(report)

# 온도편차 기준 내림차순 정렬 -> 편차가 큰 설비를 불안정 후보로 확인
print(report.sort_values("온도편차", ascending=False))
print(report.sort_values("평균진동", ascending=False))


# =========================================================
# 실습 5. 그룹별 통계량 종합
# 전체·그룹 통계와 진단표를 한 흐름으로
# =========================================================
print("=========================================================")
print("실습 5. 그룹별 통계량 종합")
print("전체·그룹 통계와 진단표를 한 흐름으로")
print("=========================================================")

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 온도 열 전체 평균·표준편차로 기준선 파악
print(df["온도"].mean().round(2))
print(df["온도"].std().round(2))

# 냉각기상태별 평균·중앙값으로 치우침 확인
print(df.groupby("냉각기상태")["온도"].agg(["mean", "median"]).round(2))

# 설비 진단표를 온도편차 순으로 정렬해 우선 점검 대상 선정
report = (
    df.groupby("밸브상태")
    .agg(평균온도=("온도", "mean"), 온도편차=("온도", "std"), 평균진동=("진동", "mean"))
    .round(2)
)
print(report)
print(report.sort_values("온도편차", ascending=False))
