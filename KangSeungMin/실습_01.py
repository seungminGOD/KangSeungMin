# 종합 실습 1. 설비 종합 모니터링 리포트
# 요구사항 자세히는 practice_guide.md 참고
# =====================================================================

sensors = [
    ("컨베이어_01", 78, 2.1),
    ("용접기_02", 92, 5.4),
    ("절단기_03", 85, 3.2),
    ("건조로_04", 101, 6.8),
    ("냉각탑_05", 67, 1.5),
    ("도장부스_06", 88, 4.1),
    ("성형기_07", 90, 2.9),
]

정상 = 0
주의 = 0
위험 = 0
온도합 = 0

최고온도 = sensors[0][1]
최고설비 = sensors[0][0]

위험설비 = []

print("=" * 40)
print("        설비 종합 모니터링 리포트")
print("=" * 40)

for i, data in enumerate(sensors, start=1):
    name, temp, vib = data

    온도합 += temp

    if temp > 최고온도:
        최고온도 = temp
        최고설비 = name

    if temp > 90 or vib > 5.0:
        상태 = "위험 🚨"
        위험 += 1
        위험설비.append(name)

    elif temp >= 80 or vib >= 3.0:
        상태 = "주의 ⚠️"
        주의 += 1

    else:
        상태 = "정상 ✅"
        정상 += 1

    print(f"{i}. {name} | 온도 {temp}℃ | 진동 {vib}mm/s | {상태}")

이상설비 = 주의 + 위험
비율 = round((이상설비 / len(sensors)) * 100, 1)

평균온도 = round(온도합 / len(sensors), 1)

위험설비.sort()

print("-" * 40)
print("총 설비:", len(sensors), "대")
print(f"정상: {정상} / 주의: {주의} / 위험: {위험}")
print(f"이상 설비 비율: {비율}%")
print(f"평균 온도: {평균온도}℃")
print(f"최고 온도 설비: {최고설비} ({최고온도}℃)")
print("위험 설비 목록:", 위험설비)
print("=" * 40)
