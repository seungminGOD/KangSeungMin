# 실습 5. 결측 순위와 행별 분석
# 정렬과 행 방향 카운트로 컬럼·행 두 방향 확인
# 컬럼 순위와 행별 결측을 함께 봐 처리 근거 모으기

# · 결측 비율을 내림차순 정렬해 가장 심한 컬럼 확인
