# [실습 9 종합 캡스톤 코드 라인 설명 주석]
# - 캡스톤 종합 분석 워크플로우:
#   1) 불러오기: usecols=(4, 5) 지정하여 회전수, 토크 2개 열 2차원 로드
#   2) 구조확인: data9.shape (40행 2열), float64 타입 검수
#   3) 추출 & 필터링: 0번 열(rpm9) 분리 후 1000 RPM 미만으로 스핀들 회전수가 떨어진 공구 고장 이상 시점 선별
#   4) 통계요약: 이상 발생 횟수(1회) 및 이상 시점 평균 회전수(58.0 RPM) 종합 리포팅
# -----------------------------------------------------------------------------
# 실습 9. NumPy 기초 종합 분석
# 데이터 불러오기, 구조 확인, 필터링, 통계를 하나의 흐름으로 수행

# · np.loadtxt로 회전수와 토크 두 열을 불러오기
data9 = np.loadtxt(
    "data/10_mct_tool.csv", delimiter=",", skiprows=1, usecols=(4, 5), encoding="utf-8"
)
print(data9)

# · shape과 dtype으로 구조 확인
print(data9.shape, data9.dtype)  # (40, 2) float64

# · 회전수가 기준 아래로 떨어진 이상 시점을 필터링해 개수와 평균 계산
rpm9 = data9[:, 0]
print(rpm9)
anomaly = rpm9[rpm9 < 1000]
print(anomaly)  # [58.]
print(anomaly.size, round(anomaly.mean(), 1))  # 1 58.0

