import numpy as np


# -----------------------------------------------------------------------------
# [실습 6 코드 라인 설명 주석]
# - 2차원 표 데이터에서 통계를 낼 때 중심축인 'axis(축)' 옵션 구분 실습입니다.
# - axis=0 (열별 / 센서별 통계 - 가장 빈번하게 사용!):
#   * 세로 방향(위에서 아래로 행을 따라 내려가며) 집계합니다.
#   * 결과로 0번 열(회전수 전체)의 평균 1829.5와 1번 열(토크 전체)의 평균 35.8이 배열로 반환됩니다.
# - axis=1 (행별 / 시점별 통계):
#   * 가로 방향(왼쪽에서 오른쪽으로 열을 따라 가며) 집계하여 각 시점의 통합 지표를 만듭니다.
# -----------------------------------------------------------------------------
# 실습 6. 센서별 기초 통계 구하기
# 표 모양 데이터에서 센서별(열별) 통계 계산
# "axis(축) 옵션 문제"

# · 여러 설비의 회전수·토크 이차원 배열 준비
data6 = np.array([[1551, 42.8], [1408, 46.3], [1498, 49.4], [2861, 4.6]])
print(data6)
# [[1551.    42.8]
#  [1408.    46.3]
#  [1498.    49.4]
#  [2861.     4.6]]

# · axis를 열 방향으로 지정해 센서별 평균 계산
print(data6.mean())  # 932.6375
print(np.round(data6.mean(axis=0), 2))  # [1829.5    35.78]

# · 센서별 표준편차 계산
print(np.round(data6.std(axis=0), 2))  # [597.73  18.15]

# 예상 결과
# 회전수·토크 각각의 평균과 표준편차가 출력

# -----------------------------------------------------------------------------
# [실습 7 코드 라인 설명 주석]
# - np.loadtxt: CSV 파일 데이터를 직접 NumPy 배열로 로드하는 함수입니다.
#   * delimiter=',': 쉼표 구분자
#   * skiprows=1: 맨 윗줄 열 이름(헤더) 1줄 건너뜀
#   * usecols=4: 4번 인덱스 열(회전수) 데이터만 선택 로드
# - 로드된 실데이터의 평균(4212.6), 표준편차(1144.9), 최솟값(58.0), 최댓값(4987.0)을 한 줄로 정량 산출합니다.
# -----------------------------------------------------------------------------
# 실습 7. 파일 데이터로 기초 통계 구하기
# 파일로 저장된 공정 데이터를 불러와 기초 통계 계산

# · np.loadtxt로 회전수 열을 파일에서 불러오기
rpm7 = np.loadtxt(
    "data/10_mct_tool.csv", delimiter=",", skiprows=1, usecols=4, encoding="utf-8"
)

# · 불러온 배열의 평균과 표준편차 계산
print(round(rpm7.mean(), 1))  # 4212.6
print(round(rpm7.std(), 1))  # 1144.9

# · 최솟값과 최댓값으로 값의 범위 확인
print(rpm7.min(), rpm7.max())  # 58.0 4987.0
print(rpm7.max() - rpm7.min())  # 4929.0

# 예상 결과
# 회전수의 평균·표준편차와 최솟값·최댓값이 출력

# -----------------------------------------------------------------------------
# [실습 8 코드 라인 설명 주석]
# - [필터링 + 통계 결합]: 데이터 분석의 궁극적 핵심 패턴입니다.
# - 1단계: 'torque8 > 50' 조건으로 토크 50 초과인 고토크 위험 시점만 'high8' 변수로 불리언 추출 [65.7, 60.7]
# - 2단계: 선별된 위험 수치들에 대해서만 평균(63.2)과 위험 발생 횟수(high8.size = 2회)를 정량 계산해냅니다.
# -----------------------------------------------------------------------------
# 실습 8. 필터링과 통계 결합하기
# 조건으로 값을 골라낸 뒤 그 값들의 통계 계산

# · 토크 배열 준비
torque8 = np.array([42.8, 46.3, 49.4, 65.7, 41.9, 60.7, 40.2, 4.6])

# · 불리언 인덱싱으로 기준을 넘는 값만 추출
high8 = torque8[torque8 > 50]
print(high8)  # [65.7 60.7]

# · 추출한 값들의 평균과 개수 계산
print(round(high8.mean(), 1))  # 63.2
print(high8.size)  # 2

