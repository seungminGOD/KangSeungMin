import pandas as pd

df = pd.read_csv("data/14_hydraulic.csv", encoding="utf-8")

# 실습 4. groupby로 그룹 집계
# 기준 → 열 → 함수 순으로 그룹별 통계 구하기
# 기준 열로 그룹을 나눠 그룹별 통계 구하기

# · 라인으로 그룹을 나눠 압력 열의 평균 집계
# 냉각기상태별 압력 평균
print(df.groupby("냉각기상태")["압력"].mean().round(2))
# 냉각기상태
# 고장    163.68
# 저하    158.49
# 정상    160.84

# · 집계 함수를 바꿔 설비별 최고 온도 확인 - max, min
# 벨브상태별로 최고 온도
print(df.groupby("밸브상태")["온도"].max())
# 밸브상태
# 경미    57.1
# 심각    57.6
# 정상    57.8
# 지연    57.5

# · size로 교대별 측정 건수까지 확인
# 운전부하별로 size로 갯수 세기 (결측-null값 갯수도 포함)
print(df.groupby("운전부하").size())
# 운전부하
# 고부하    60
# 저부하    60

# 예상 결과
# 라인별 평균 압력·설비별 최고 온도·교대별 건수 출력

print("--------------------------------------")

# 실습 5. 그룹별 평균 비교와 정렬
# 그룹별 평균을 구해 정렬로 두드러진 그룹 찾기
# 그룹별 평균을 구하고 정렬해 두드러진 그룹 찾기

# · 설비로 그룹을 나눠 진동 평균 집계
# 밸브상태 그룹별로 진동의 평균
print(df.groupby("밸브상태")["진동"].mean().round(3))
# 밸브상태
# 경미    0.617
# 심각    0.629
# 정상    0.609
# 지연    0.621

# · 집계 결과에 정렬을 이어 붙여 내림차순으로 정렬
# 앞선 평균결과에 맞춰서 심각 > 지연 > 경미 > 정상 순서로 출력
print(df.groupby("밸브상태")["진동"].mean().round(3).sort_values(ascending=False))
# 밸브상태
# 심각    0.629
# 지연    0.621
# 경미    0.617
# 정상    0.609

# · 가장 진동이 큰 설비를 맨 위에서 확인
# 앞선 결과에서 심각 0.629가 맨 윗줄인걸 확인. 끝.

