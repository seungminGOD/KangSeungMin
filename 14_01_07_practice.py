# · value_counts로 설비 구성과 정상·고장 비율 파악
# 밸브상태별로 비율 확인 - 일단 각 상태별로 몇건이 있는지 확인
# group-size와 다르게 여기는 counts라서 결측(null값) 무시
print(df["밸브상태"].value_counts())
# 밸브상태
# 정상    61
# 지연    20
# 경미    20
# 심각    19

print(df["밸브상태"].value_counts(normalize=True).round(3))
# 밸브상태
# 정상    0.508
# 지연    0.167
# 경미    0.167
# 심각    0.158

