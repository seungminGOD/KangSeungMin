# 실습 2. 한 컬럼의 최소·최대·범위
# 실린더압력의 양 끝값과 범위로 퍼짐 확인

# 한 컬럼의 최솟값·최댓값·범위를 구해 퍼짐 확인
# · 실린더압력 열의 최솟값 구하기
print(df['실린더압력'].min()) # 108.0

# · 실린더압력 열의 최댓값 구하기
print(df['실린더압력'].max()) # 265.0

# · 최댓값에서 최솟값을 빼 범위 계산
range = df['실린더압력'].max() - df['실린더압력'].min()
print(range) # 157.0

