# 5. temps = [55, 62, 71, 68] → for로 하나씩 출력
#    힌트: for t in temps:
# (여기에 작성)

temps = [55, 62, 71, 68]
for t in temps:
    print(t)


# 6. temps = [55, 62, 71, 68] → 70 초과일 때만 "과열" 출력
#    (if + for 합치기)
# (여기에 작성)

temps = [55, 62, 71, 68]
for t in temps:
    if t > 70:
        print("과열")


# 7. for로 5번 반복하며 "샷", 번호 출력
